import { existsSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = resolve(here, "..", "..");
export const GENERATED_FILE = resolve(here, "..", "src", "generated", "forbiddenHosts.ts");

const DEMO_YML = join("src", "main", "resources", "application-demo.yml");
const LAB_PROPERTIES = join("src", "main", "java", "com", "settlementengine", "core", "lab", "LabProperties.java");

function split(list: string): string[] {
  return list
    .split(",")
    .map((h) => h.trim().replace(/^["']|["']$/g, ""))
    .filter((h) => h.length > 0);
}

/**
 * Reads the staging host list from the backend's own config: the value in application-demo.yml and
 * the default in LabProperties. The two must agree, or this throws. Returns null outside a repo
 * checkout (for example in a published copy), where the committed generated file is used as is.
 */
export function readForbiddenHosts(repoRoot: string = REPO_ROOT): string[] | null {
  const ymlPath = join(repoRoot, DEMO_YML);
  const javaPath = join(repoRoot, LAB_PROPERTIES);
  if (!existsSync(ymlPath) || !existsSync(javaPath)) return null;

  const yml = /^\s*forbidden-hosts:\s*(.+?)\s*$/m.exec(readFileSync(ymlPath, "utf8"));
  const java = /@DefaultValue\("([^"]*)"\)\s*List<String>\s+forbiddenHosts/.exec(readFileSync(javaPath, "utf8"));
  if (!yml?.[1] || !java?.[1]) {
    throw new Error("Could not find forbidden-hosts in application-demo.yml or LabProperties.java");
  }
  const fromYml = split(yml[1]);
  const fromJava = split(java[1]);
  if (JSON.stringify(fromYml) !== JSON.stringify(fromJava)) {
    throw new Error(
      `forbidden-hosts differ: application-demo.yml has [${fromYml.join(", ")}], LabProperties default has [${fromJava.join(", ")}]`,
    );
  }
  return fromYml;
}

export function renderGenerated(hosts: readonly string[]): string {
  return [
    "// Generated by scripts/sync-forbidden-hosts.ts from the backend's settlement-engine.demo.forbidden-hosts",
    "// (application-demo.yml and the LabProperties default). Do not edit by hand: the unit test",
    "// forbiddenHostsSync.test.ts fails if this file drifts from the backend config.",
    `export const FORBIDDEN_HOSTS: readonly string[] = ${JSON.stringify(hosts)};`,
    "",
  ].join("\n");
}
